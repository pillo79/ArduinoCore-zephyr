# This script packs all sketch compilation reports of a CI test run into a
# single JSON file, to be stored in ci-builds as test run metadata.
#
# Expects the CORE_VER, CORE_HASH, CORE_BRANCH and ALL_BOARD_FQBNS environment
# variables (see ci_get_build_info.sh) and the standard GitHub Actions
# environment variables (GITHUB_REPOSITORY, GITHUB_EVENT_NAME, GITHUB_RUN_ID,
# GITHUB_RUN_ATTEMPT).
#
# The output is consumed by external tools, so its format must be kept stable.
# Any incompatible change must increase 'format_version'. Current format:
#
#   {
#     "format_version": 1,
#     "core_version": CORE_VER,
#     "core_hash": CORE_HASH,
#     "core_branch": CORE_BRANCH,
#     "repository": GITHUB_REPOSITORY,
#     "event": GITHUB_EVENT_NAME,
#     "run_id": GITHUB_RUN_ID,
#     "run_attempt": GITHUB_RUN_ATTEMPT,
#     "timestamp": "<UTC time, ISO 8601>",
#     "reports": {
#       "<fqbn>": {
#         "board": "<fqbn>",
#         "sketches": [
#           {
#             "name": "<sketch path>",
#             "compilation_success": true|false,
#             "sizes": [
#               { "name": "flash" | "RAM for global variables",
#                 "maximum": <bytes>,
#                 "current": { "absolute": <bytes>, "relative": <percent> } },
#               ...
#             ],
#             "issues": [ "<warning or error message>", ... ]
#           },
#           ...
#         ],
#         ...
#       },
#       ...
#     }
#   }
#
# Each "reports" entry is the board report generated by compile-sketches.
# All tested FQBNs are always present: an empty object means the test job for
# that FQBN failed and produced no report.
#
# The file is written to <output_dir> as 'test_info.json', or with --daily as
# 'test_info-<timestamp>.json' (UTC, YYYYmmddTHHMMSSZ), so that the results of
# periodic runs of the same core version are kept apart. In ci-builds, these
# are stored as '<version>-test_info[-<timestamp>].json': re-runs of the same
# workflow run replace the file of their first attempt.
#
# Usage: ci_pack_test_results.sh <reports_dir> <output_dir> [--daily]

set -e

if [ $# -lt 2 ] || [ $# -gt 3 ] || { [ $# -eq 3 ] && [ "$3" != "--daily" ]; }; then
	echo "Usage: $0 <reports_dir> <output_dir> [--daily]"
	exit 1
fi

REPORTS_DIR=$1
OUTPUT_DIR=$2
NOW=$(date -u '+%s')
if [ "$3" == "--daily" ]; then
	OUTPUT_FILE="$OUTPUT_DIR/test_info-$(date -u -d "@$NOW" '+%Y%m%dT%H%M%SZ').json"
else
	OUTPUT_FILE="$OUTPUT_DIR/test_info.json"
fi

mkdir -p "$OUTPUT_DIR"
jq -n \
	--arg core_version "$CORE_VER" \
	--arg core_hash "$CORE_HASH" \
	--arg core_branch "$CORE_BRANCH" \
	--arg repository "$GITHUB_REPOSITORY" \
	--arg event "$GITHUB_EVENT_NAME" \
	--argjson run_id "$GITHUB_RUN_ID" \
	--argjson run_attempt "$GITHUB_RUN_ATTEMPT" \
	--argjson all_board_fqbns "$ALL_BOARD_FQBNS" \
	--arg timestamp "$(date -u -d "@$NOW" '+%Y-%m-%dT%H:%M:%SZ')" \
	'{
		format_version: 1,
		$core_version, $core_hash, $core_branch,
		$repository, $event, $run_id, $run_attempt, $timestamp,
		reports: (
			($all_board_fqbns | map({ key: "arduino:\(.subarch):\(.board):link_mode=\(.link_mode)", value: {} }) | from_entries)
			+ reduce (inputs | .boards[0]? // empty) as $b ({}; .[$b.board] = $b)
		)
	}' "$REPORTS_DIR"/*.json > "$OUTPUT_FILE"
