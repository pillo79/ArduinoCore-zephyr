# Script to analyze CI build and test logs and collect results into a JSON file.
#
# The script reads build artifacts and test reports generated during a GitHub
# Actions CI run for Arduino Zephyr cores. It aggregates results by board,
# artifact, and sketch, and serializes all data to a JSON file for further
# processing by ci_generate_report.py.
#
# This script expects the following inputs:
#
#  - Environment variables:
#     - ALL_BOARD_DATA: JSON array of all board metadata, generated by get_board_details.sh
#     - GITHUB_REPOSITORY, GITHUB_RUN_ID: workflow context variables for writing links
#     - NATIVE_SIM_BOARD_DATA: native_sim board metadata, as in ALL_BOARD_DATA (not reported if unset)
#     - NATIVE_SIM_MATRIX: native_sim test jobs, see ci_native_sim_matrix.sh
#
#  - Files in the current directory:
#     - zephyr-<variant>.config: Kconfig settings, generated at loader build time
#     - zephyr-<variant>.warnings: Loader compilation warnings
#     - zephyr-<variant>.meminfo: Loader memory usage report
#     - arduino-<subarch>-<board>-link_mode=<mode>.json: Compilation test report files
#     - variants/<variant>/known_example_issues.txt: Expected errors for that variant
#     - prereqs/<id>.json: job completion markers with job status and log links, see ci_filter_matrix.sh
#     - native_sim-sketches-<group>.json: native_sim test reports, one per test job, see
#       loader/native_sim/tests/run_sketches.sh
#
# This script produces one output file:
#
#  - <json_file>: JSON file with all collected data, to be consumed by ci_generate_report.py
#
# Usage: ci_collect_data.py [--exclude-artifact <artifact>]... [<json_file>]
#  If no file is given, output is written to /dev/stdout.
#  --exclude-artifact leaves the boards and tests of that artifact out of the
#  output, and out of the overall result.

import argparse
import copy
from collections import defaultdict
import glob
import json
import os
import re
import sys

import ci_shared
from ci_shared import (
    TestStatus, SKIP, PASS, WARNING, EXPECTED_ERROR, INVALID_EXCEPTION, ERROR, FAILURE,
    LoaderEntry, TestEntry, TestGroup,
    load_known_issues, load_sketch_reports, evaluate_sketch,
)

# Global Data Structures
# ----------------------

# Loader build results, one per board
BOARD_LOADERS = {}                                          # { board: LoaderEntry() }

ALL_TESTS = []                                               # [ TestEntry() ]

# Test results grouped by artifact, board, and artifact/sketch
# (grouping sketch results across different artifacts is really confusing)
ARTIFACT_TESTS = defaultdict(TestGroup)                     # { artifact: TestGroup() }
BOARD_TESTS = defaultdict(TestGroup)                        # { board: TestGroup() }
SKETCH_TESTS = defaultdict(lambda: defaultdict(TestGroup))  # { artifact: { sketch: TestGroup() } }

def track_test(test_entry):
    """
    Logs a test entry into the global test tracking structures.
    """
    ARTIFACT_TESTS[test_entry.artifact].track(test_entry)
    BOARD_TESTS[test_entry.board].track(test_entry)
    SKETCH_TESTS[test_entry.artifact][test_entry.sketch].track(test_entry)
    ALL_TESTS.append(test_entry)

# ---------------------------------------------------------------------------
# Main Logic
# ---------------------------------------------------------------------------

# Environment Variable Checks
ALL_BOARD_DATA_STR = os.environ.get('ALL_BOARD_DATA')
GITHUB_REPOSITORY = os.environ.get('GITHUB_REPOSITORY')
GITHUB_RUN_ID = os.environ.get('GITHUB_RUN_ID')
JOB_LINK_STEM = f"https://github.com/{GITHUB_REPOSITORY}/actions/runs/{GITHUB_RUN_ID}"

if not ALL_BOARD_DATA_STR or not GITHUB_REPOSITORY or not GITHUB_RUN_ID:
    print("Not in a Github CI run, cannot proceed.")
    sys.exit(0)

parser = argparse.ArgumentParser(description="Collect the CI results into a JSON file.")
parser.add_argument('--exclude-artifact', action='append', default=[], metavar='ARTIFACT',
                    help="leave the boards and tests of this artifact out of the output")
parser.add_argument('json_file', nargs='?', default="/dev/stdout")
args = parser.parse_args()
json_file = args.json_file

# Load board data from environment variables
ALL_BOARD_DATA = json.loads(ALL_BOARD_DATA_STR)
ALL_BOARD_DATA = { b['board']: b for b in ALL_BOARD_DATA }

# native_sim is not part of the core artifacts: its board data comes separately
NATIVE_SIM_BOARD_DATA_STR = os.environ.get('NATIVE_SIM_BOARD_DATA')
NATIVE_SIM_MATRIX = json.loads(os.environ.get('NATIVE_SIM_MATRIX') or '[]')
def mimic_id(board):
    """
    Returns the id of the board of native_sim posing as a board.
    """
    return f"native_sim:{board}"

if NATIVE_SIM_BOARD_DATA_STR:
    native_sim_data = json.loads(NATIVE_SIM_BOARD_DATA_STR)
    ALL_BOARD_DATA[native_sim_data['board']] = native_sim_data
    # native_sim posing as each board is reported as a board of its own, in
    # the native_sim artifact, with the test job of that board
    for job in NATIVE_SIM_MATRIX:
        if job.get('variant'):
            board_id = mimic_id(job['group'])
            ALL_BOARD_DATA[board_id] = dict(native_sim_data, board=board_id, mimic=job['group'],
                                            mimic_variant=job['variant'], mimic_job=job['id'])

# Load job statuses and URLs from the job completion markers
JOB_STATUS = {}
JOB_URLS = {}
for marker_file in glob.glob("prereqs/*.json"):
    with open(marker_file, 'r') as f:
        marker = json.load(f)
    JOB_STATUS[marker['id']] = marker['status']
    JOB_URLS[marker['id']] = marker['job_url']

def job_failed(job_id):
    """
    Returns True if the job completed without success. Jobs that did not
    publish a marker are not considered failed, as their status is unknown.
    """
    return JOB_STATUS.get(job_id, 'success') != 'success'

def job_succeeded(job_id):
    """
    Returns True if the job completed successfully. Jobs that did not
    publish a marker did not complete, as for ci_filter_matrix.sh.
    """
    return JOB_STATUS.get(job_id) == 'success'

REGIONS_BY_SOC = defaultdict(set)     # { soc: set(regions) }

def process_board(board_data, native_sim_failed):
    """
    Collects the loader and test data of a board. native_sim_failed tells
    whether the native_sim tests of the board failed, so that its core
    package was not tested.
    """
    # Extract common fields from board data
    artifact = board_data['artifact']
    board = board_data['board']
    variant = board_data['variant']
    subarch = board_data['subarch']

    # Get job link for this build
    job_link = JOB_URLS.get(board_data['id'])
    if job_link:
        job_link += "#step:5:1"

    # Read loader build data (native_sim posing as a board shares the loader
    # of native_sim, processed first: its warnings are only reported once)
    native_sim = artifact == 'native_sim'
    mimic = board_data.get('mimic')
    if mimic and 'native_sim' in BOARD_LOADERS:
        BOARD_LOADERS[board] = copy.copy(BOARD_LOADERS['native_sim'])
        BOARD_LOADERS[board].board = board
        BOARD_LOADERS[board].warnings = []
    else:
        BOARD_LOADERS[board] = LoaderEntry(artifact, board, variant, job_link, need_meminfo=not native_sim)
    if job_failed(board_data['id']):
        # the build may have failed after producing the core data
        BOARD_LOADERS[board].status = FAILURE
    if BOARD_LOADERS[board].status == FAILURE:
        track_test(TestEntry.failure("Core data could not be read.", artifact, board))
        return

    # Get SoC-specific info from loader config
    soc = BOARD_LOADERS[board].config['CONFIG_SOC']
    board_data['soc'] = soc
    REGIONS_BY_SOC[soc].update(BOARD_LOADERS[board].meminfo.keys())

    # Get list of expected errors for this board (and, for native_sim posing
    # as a board, the ones of that board)
    exceptions, warning_filters = load_known_issues(variant, mimic and (mimic, board_data['mimic_variant']))

    if native_sim:
        # one report per test job, built and run with the package of the build
        # job: the job posing as the board, or the ones common to all boards
        jobs = [ job for job in NATIVE_SIM_MATRIX if job.get('variant') is None ] if not mimic \
               else [ job for job in NATIVE_SIM_MATRIX if job['id'] == board_data['mimic_job'] ]
        for job in jobs:
            group, job_id = job['group'], job['id']
            job_link = JOB_URLS.get(job_id)
            reports, error = load_sketch_reports(f"native_sim-sketches-{group}.json")
            if error:
                # a job that wrote its report completed its tests, even if it
                # failed on them: only a missing report is shown, with the
                # sketches of the group
                track_test(TestEntry(artifact, board, f"CI test {group}", "static", False, FAILURE,
                                     [ f"{group}: tests did not complete." ], job_link,
                                     group=group, name="CI test"))
            for report in reports:
                sketch, excepted, status, sketch_issues = evaluate_sketch(report, exceptions, warning_filters)
                track_test(TestEntry(artifact, board, sketch, "static", excepted, status, sketch_issues, job_link,
                                     run_success=report.get('run_success')))
        return

    # Tests are not run if the core package was not built: blame the package
    # job if it failed, or skip them if a board build prevented the packaging
    # (the failed build is reported on its own board)
    package_id = f"package-{artifact}"
    if job_failed(package_id):
        track_test(TestEntry.failure("Core package build failed.", artifact, board, JOB_URLS.get(package_id)))
        return
    # (tests that produced a report did run, and are always evaluated)
    if package_id not in JOB_STATUS \
       and not glob.glob(f"arduino-{subarch}-{board}-link_mode=*.json") \
       and any(not job_succeeded(b['id']) for b in ALL_BOARD_DATA.values() if b['artifact'] == artifact):
        track_test(TestEntry.skipped("Core package was not built, tests skipped.", artifact, board))
        return
    # test-core does not start if the native_sim tests failed: the board
    # was not tested, which is not a failure of its own
    if native_sim_failed and not glob.glob(f"arduino-{subarch}-{board}-link_mode=*.json"):
        track_test(TestEntry.skipped("Tests not run, as the native_sim tests failed.", artifact, board))
        return

    # Get raw data from report files for both static and dynamic linking modes
    for link_mode in ("static", "dynamic"):
        # Get job link for this test
        job_link = JOB_URLS.get(f"test-{board}-{link_mode}")
        if job_link:
            job_link += "#step:7:1"

        # Extract data from the report file
        report_file = f"arduino-{subarch}-{board}-link_mode={link_mode}.json"
        reports, error = load_sketch_reports(report_file)
        if error:
            track_test(TestEntry.failure(f"{link_mode.capitalize()} link mode: {error}", artifact, board, job_link))
            continue # Skip to the next board

        # Iterate through individual sketch reports
        for report in reports:
            sketch, excepted, status, sketch_issues = evaluate_sketch(report, exceptions, warning_filters)

            # Log the test result to all data structures
            track_test(TestEntry(artifact, board, sketch, link_mode, excepted, status, sketch_issues, job_link))


# Import and process data for each board: native_sim first, as the core
# package of a board is not tested if the native_sim tests common to all
# boards, or the ones posing as that board, failed
for board, board_data in ALL_BOARD_DATA.items():
    if board_data['artifact'] == 'native_sim':
        process_board(board_data, False)

def native_sim_failed(board):
    """
    Returns True if the native_sim tests that test-core requires for the
    board failed (see test_core.yml).
    """
    return any(b in BOARD_TESTS and not BOARD_TESTS[b].status.passed
               for b in ('native_sim', mimic_id(board)))

for board, board_data in ALL_BOARD_DATA.items():
    if board_data['artifact'] != 'native_sim':
        process_board(board_data, native_sim_failed(board))

# Leave the excluded artifacts out of the output, after all boards were
# processed (their results may affect the other boards)
ARTIFACTS = sorted(a for a in ARTIFACT_TESTS.keys() if a not in args.exclude_artifact)
OUTPUT_BOARDS = { board: board_data for board, board_data in ALL_BOARD_DATA.items()
                  if board_data['artifact'] not in args.exclude_artifact }
OUTPUT_SOCS = { board_data.get('soc') for board_data in OUTPUT_BOARDS.values() }

ci_run_status = max(ARTIFACT_TESTS[artifact].status for artifact in ARTIFACTS)
ci_run_passed = ci_run_status.passed

# Serialize all data to JSON
output = {
    'job_link_stem': JOB_LINK_STEM,
    'artifacts': ARTIFACTS,
    'ci_run_passed': ci_run_passed,
    'all_board_data': OUTPUT_BOARDS,
    'regions_by_soc': {soc: list(regions) for soc, regions in REGIONS_BY_SOC.items() if soc in OUTPUT_SOCS},
    'board_loaders': {board: loader.to_dict() for board, loader in BOARD_LOADERS.items() if board in OUTPUT_BOARDS},
    'all_tests': [t.to_dict() for t in ALL_TESTS if t.artifact not in args.exclude_artifact],
}

with open(json_file, 'w') as f:
    json.dump(output, f)
